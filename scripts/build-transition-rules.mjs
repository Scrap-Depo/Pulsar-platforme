import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const canonical = read('firestore.rules');
const previous = read('deployment/pulsar-5692c/previous-firestore.rules');
const inspection = JSON.parse(read('deployment/pulsar-5692c/inspection.json'));
assert.equal(
  createHash('sha256').update(previous).digest('hex'),
  inspection.previousRulesSha256,
  'The inspected legacy rules changed. Review a new cloud snapshot before composing rules.',
);
const prefix =
  "rules_version = '2';\n\nservice cloud.firestore {\n  match /databases/{database}/documents {\n";
const suffix = '\n  }\n}\n';
assert.ok(previous.startsWith(prefix) && previous.endsWith(suffix), 'Unexpected legacy format.');
const legacy = previous.slice(prefix.length, -suffix.length);
assert.ok(legacy.includes('match /sessions/{sessionId}'));
assert.ok(!legacy.includes('match /{document=**}'), 'Legacy rules must not cover v2 paths.');
assert.ok(!canonical.includes('function signedIn('), 'Legacy helper collides with v2 helper.');
const anchor = '    match /{document=**} { allow read, write: if false; }';
assert.equal(canonical.split(anchor).length, 2, 'Expected one default-deny rule.');
const comment =
  "    // All writes go through authenticated callable functions. Legacy sessions are\n    // intentionally not made accessible by this new application's rules.";
const generated =
  '// Generated by scripts/build-transition-rules.mjs for pulsar-5692c only.\n' +
  canonical
    .replace(
      comment,
      '    // v2 writes use callable functions; legacy access below is preserved for migration.',
    )
    .replace(
      anchor,
      `    // Existing cloud rules, restricted to the old /sessions tree.\n${legacy}\n\n${anchor}`,
    );
const destination = new URL('deployment/pulsar-5692c/firestore.rules', root);
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(destination, 'utf8'), generated, 'Run npm run prepare:transition.');
  console.log('Transition rules match current v2 rules and inspected legacy rules.');
} else {
  writeFileSync(destination, generated);
  console.log('Prepared transition rules for pulsar-5692c; no cloud changes.');
}
